"""Builds the single-file edition of Font Sleuth by joining the package modules in dependency order.

Usage: python tools/make_single_file.py [output.py]
The script refuses to build if two modules define the same top-level name (they would overwrite each other).
"""

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "src" / "fontsleuth"
INTERNAL = re.compile(r"^(from fontsleuth(\.\w+)? import .*|import fontsleuth.*)$")
SKIP = {"__main__"}


def module_names() -> list[str]:
    """Returns the package's module names, excluding __init__ and __main__."""
    return sorted(p.stem for p in PACKAGE.glob("*.py") if p.stem not in SKIP and p.stem != "__init__")


def dependencies(name: str) -> set[str]:
    """Returns the other package modules that a module imports."""
    tree = ast.parse((PACKAGE / f"{name}.py").read_text(encoding="utf-8"))
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module and node.module.startswith("fontsleuth."):
            found.add(node.module.split(".")[1])
    return found - {name}


def ordered() -> list[str]:
    """Sorts modules so every module comes after the modules it imports."""
    remaining, done, result = set(module_names()), set(), []
    while remaining:
        ready = sorted(m for m in remaining if dependencies(m) <= done)
        if not ready:
            raise SystemExit(f"Circular imports among: {sorted(remaining)}")
        result.append(ready[0])
        done.add(ready[0])
        remaining.remove(ready[0])
    return result


def top_level_names(name: str) -> set[str]:
    """Returns the names a module defines at top level (classes, functions, constants)."""
    names = set()
    for node in ast.parse((PACKAGE / f"{name}.py").read_text(encoding="utf-8")).body:
        if isinstance(node, (ast.ClassDef, ast.FunctionDef)):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            names.update(t.id for t in node.targets if isinstance(t, ast.Name))
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
    return names


def check_collisions(order: list[str]) -> None:
    """Stops the build if two modules define the same top-level name."""
    owners: dict[str, str] = {}
    for name in order:
        for defined in top_level_names(name):
            if defined in owners:
                raise SystemExit(f"Name '{defined}' is defined in both {owners[defined]}.py and {name}.py")
            owners[defined] = name


def body_of(name: str) -> str:
    """Returns a module's source without its docstring and its imports of other package modules."""
    source = (PACKAGE / f"{name}.py").read_text(encoding="utf-8")
    tree = ast.parse(source)
    lines = source.splitlines()
    if tree.body and isinstance(tree.body[0], ast.Expr) and isinstance(getattr(tree.body[0], "value", None), ast.Constant):
        lines = lines[tree.body[0].end_lineno:]
    kept = [line for line in lines if not INTERNAL.match(line)]
    return "\n".join(kept).strip("\n")


def build() -> str:
    """Assembles the whole single-file program text."""
    order = ordered()
    check_collisions(order)
    version = re.search(r'__version__ = "([^"]+)"', (PACKAGE / "__init__.py").read_text(encoding="utf-8")).group(1)
    parts = [
        '"""Font Sleuth - single-file edition. Finds the font, weight, size and colour of text in pictures and PDFs.\n\n'
        'Generated by tools/make_single_file.py from the source folders; edit those, not this file.\n'
        'Run with:  python fontsleuth.py   (needs: pip install PyQt6 PyMuPDF Pillow numpy fonttools)\n"""\n',
        f'__version__ = "{version}"\n',
    ]
    for name in order:
        parts.append(f"\n# {'=' * 20} {name}.py {'=' * 20}\n{body_of(name)}\n")
    parts.append('\n\nif __name__ == "__main__":\n    import sys\n\n    sys.exit(Application.run(sys.argv))\n')
    return "".join(parts)


def main() -> int:
    """Writes the single file (default: dist/fontsleuth.py) and checks that it compiles."""
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "dist" / "fontsleuth.py"
    text = build()
    compile(text, str(target), "exec")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print(f"Wrote {target} ({len(text.splitlines())} lines, {len(ordered())} modules)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
